const languageOrder = ['HTML', 'CSS', 'JavaScript', 'Python', 'Java', 'C++', 'SQL']

export function getEligibleCodingPracticeTests(completedTopics) {
  const testsByLanguage = new Map()
  for (const topic of completedTopics) {
    const configuredChallenge = challengeByTopic[topicAliases[topic] || topic]
    if (!configuredChallenge) continue
    const challenge = { ...configuredChallenge, topic }
    const test = testsByLanguage.get(challenge.language) || {
      id: `career-${challenge.language.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
      language: challenge.language,
      subject: challenge.language,
      questions: [],
      topics: [],
      difficulty: 'Beginner',
      source: 'Sample coding challenges',
    }
    if (!test.questions.some((question) => question.id === challenge.id)) test.questions.push(challenge)
    if (!test.topics.includes(topic)) test.topics.push(topic)
    testsByLanguage.set(challenge.language, test)
  }
  return [...testsByLanguage.values()]
    .sort((left, right) => languageOrder.indexOf(left.language) - languageOrder.indexOf(right.language))
    .map((test) => ({ ...test, durationMinutes: Math.max(1, test.questions.length * 3) }))
}
